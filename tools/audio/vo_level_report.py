#!/usr/bin/env python3
"""Level report for the mastered voice-over (audio-plan section 2.3: VO -18 LUFS-I, <= -1.5 dBTP).

Measures every `vo` asset of web/public/audio/manifest.json with ffmpeg's ebur128 filter (true-peak
mode, dual-mono: a mono line plays on both channels of the stereo voice bus) on the delivered .ogg and
.m4a, adds the loudness range (LRA), the leading/trailing silence of the decoded .ogg and the trim the
mastering applied, and writes

  tools/audio/reports/vo-levels.json   every line
  tools/audio/reports/vo-levels.md     per-role summary + the per-line table

Exit code 1 if any line misses -18 +-1 LU or exceeds the true-peak ceiling (m4a: +0.5 dB AAC grace).
Usage: python3 tools/audio/vo_level_report.py
"""

from __future__ import annotations

import json
import math
import re
import statistics
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import audiolib as A  # noqa: E402

ROOT = HERE.parents[1]
OUT = ROOT / "web" / "public" / "audio"
REPORTS = HERE / "reports"
TOL = 1.0
M4A_TP_GRACE = 0.5
_LRA = re.compile(r"LRA:\s+(-?[\d.]+|-inf) LU\s*$", re.M)


def lra(path: Path) -> float:
    proc = subprocess.run(
        [A.FFMPEG, "-hide_banner", "-nostats", "-nostdin", "-i", str(path), "-af", "ebur128=dualmono=true", "-f", "null", "-"],
        capture_output=True, text=True,
    )
    m = _LRA.findall(proc.stderr)
    return float(m[-1]) if m and m[-1] != "-inf" else math.nan


def main() -> int:
    manifest = json.loads((OUT / "manifest.json").read_text())
    cls = manifest["classes"]["vo"]
    rows, failures = [], []
    for e in manifest["assets"]:
        if e["kind"] != "vo":
            continue
        row = {"id": e["id"], "line": e.get("line"), "role": e.get("role"), "durationSec": e["durationSec"],
               "trimmedMs": round((e.get("trimmedFromSec", e["durationSec"]) - e["durationSec"]) * 1000)}
        for fmt in ("ogg", "m4a"):
            p = OUT / e["files"][fmt]
            m = A.ffmpeg_ebur128(p, dual_mono=True)
            row[f"{fmt}LufsI"] = round(m["lufsI"], 2)
            row[f"{fmt}TruePeak"] = round(m["truePeak"], 2)
            row[f"{fmt}Bytes"] = p.stat().st_size
            if abs(m["lufsI"] - cls["target"]) > TOL:
                failures.append(f"{e['id']} [{fmt}]: {m['lufsI']:.2f} LUFS vs {cls['target']} +-{TOL}")
            if m["truePeak"] > cls["tpMax"] + (M4A_TP_GRACE if fmt == "m4a" else 0):
                failures.append(f"{e['id']} [{fmt}]: true peak {m['truePeak']:.2f} dBTP")
        ogg = OUT / e["files"]["ogg"]
        row["lra"] = round(lra(ogg), 1)
        pcm = A.decode(ogg, 1)
        row["headMs"] = round(A.head_silence(pcm, threshold_db=-50) * 1000)
        row["tailMs"] = round(A.tail_silence(pcm, threshold_db=-50) * 1000)
        rows.append(row)

    REPORTS.mkdir(exist_ok=True)
    (REPORTS / "vo-levels.json").write_text(json.dumps({"target": cls["target"], "tpMax": cls["tpMax"], "lines": rows,
                                                         "failures": failures}, indent=2) + "\n")

    def stats(sel: list[dict], key: str) -> str:
        v = [r[key] for r in sel if isinstance(r[key], (int, float)) and math.isfinite(r[key])]
        return f"{min(v):.1f} / {statistics.mean(v):.1f} / {max(v):.1f}" if v else "-"

    md = ["# Mastered VO: level report", "",
          f"ffmpeg `ebur128` (true peak, dual-mono) on the delivered files in `web/public/audio/vo`. Target "
          f"{cls['target']} LUFS-I ±{TOL:.0f} LU, true peak ≤ {cls['tpMax']} dBTP (m4a +{M4A_TP_GRACE} dB AAC grace). "
          f"Generated by `python3 tools/audio/vo_level_report.py`.", "",
          "| Role | Lines | LUFS-I .ogg (min / mean / max) | LUFS-I .m4a | True peak .ogg | True peak .m4a | LRA (LU) | Duration (s) | Head / tail silence (ms, max) | Trimmed (ms, mean) | Size .ogg / .m4a |",
          "|---|---:|---|---|---|---|---|---|---|---:|---|"]
    for role in ("advisor", "anchor", None):
        sel = [r for r in rows if role is None or r["role"] == role]
        if not sel:
            continue
        md.append(
            f"| {role or '**all**'} | {len(sel)} | {stats(sel, 'oggLufsI')} | {stats(sel, 'm4aLufsI')} | {stats(sel, 'oggTruePeak')} | "
            f"{stats(sel, 'm4aTruePeak')} | {stats(sel, 'lra')} | {stats(sel, 'durationSec')} | "
            f"{max(r['headMs'] for r in sel)} / {max(r['tailMs'] for r in sel)} | {statistics.mean(r['trimmedMs'] for r in sel):.0f} | "
            f"{sum(r['oggBytes'] for r in sel) / 1048576:.2f} / {sum(r['m4aBytes'] for r in sel) / 1048576:.2f} MB |")
    md += ["", f"**{'FAILED: ' + str(len(failures)) if failures else 'All'} {'' if failures else str(len(rows)) + ' lines within target.'}**", ""]
    md += ["| Line | Role | s | LUFS .ogg | LUFS .m4a | TP .ogg | TP .m4a | LRA | head ms | tail ms |", "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for r in sorted(rows, key=lambda r: (r["role"] or "", r["line"] or "")):
        md.append(f"| {r['line']} | {r['role']} | {r['durationSec']:.2f} | {r['oggLufsI']:.1f} | {r['m4aLufsI']:.1f} | {r['oggTruePeak']:.1f} | "
                  f"{r['m4aTruePeak']:.1f} | {r['lra']:.1f} | {r['headMs']} | {r['tailMs']} |")
    (REPORTS / "vo-levels.md").write_text("\n".join(md) + "\n")
    print("\n".join(md[:9]))
    for f in failures:
        print("FAIL " + f)
    print(f"\nvo-level-report {'FAILED' if failures else 'OK'} ({len(rows)} lines) -> {A.rel(REPORTS / 'vo-levels.md', ROOT)}")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
