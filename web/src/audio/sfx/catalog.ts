// Every SFX id the client can request (audio-plan §6.2), with its class, polyphony, cooldown, voice
// priority, detune policy and sources: mastered files from the manifest (KEEP / future GENERATE takes)
// and procedural recipes. Rules (§4.10): variants from a shuffle bag; ±30 c random detune on
// non-musical sounds, 0 on musical ones; per-id polyphony 3 (UI 2, world 2, stingers 1); global cap 24;
// cooldowns as listed.

import { dbToGain } from '../core/math';
import { FALLBACK_RECIPES } from '../synth/fallbacks';
import { STINGER_RECIPES } from '../synth/music';
import { peakGuard } from '../synth/primitives';
import { PROC_RECIPES, type RecipeDef, type SfxClass } from '../synth/recipes';
import calibration from '../synth/calibration.json';

export const ALL_RECIPES: Readonly<Record<string, RecipeDef>> = { ...PROC_RECIPES, ...FALLBACK_RECIPES, ...STINGER_RECIPES };

const CALIBRATION = calibration as { trims: Record<string, number>; peakLimited?: string[] };

/** Per-recipe trim in dB to land on the class target (generated by tools/audio/recipe-levels.mjs). */
export const RECIPE_TRIM_DB: Readonly<Record<string, number>> = CALIBRATION.trims;

/**
 * Recipes whose loudness target is out of reach under their class peak ceiling (transients shorter
 * than the 400 ms momentary window): the calibration holds them at the ceiling instead.
 */
export const PEAK_LIMITED: ReadonlySet<string> = new Set(CALIBRATION.peakLimited ?? []);

export interface SfxSpec {
  id: string;
  cls: SfxClass;
  /** UI cues go to uiIn (never ducked); the rest to sfxIn (ducked −3 dB under VO). */
  ui: boolean;
  cooldownMs: number;
  maxVoices: number;
  /** Voice-stealing priority (higher survives). */
  priority: number;
  /** Random detune range for file variants (recipes carry their own). */
  fileDetune: number;
  /** Procedural recipes that can play this id. */
  recipes: string[];
  /** 'fallback': recipes only while the manifest has no file; 'mix': files and recipes share the bag. */
  mode: 'fallback' | 'mix';
  /** Procedural layer always played on top of a file variant (ribbon_cut chime). */
  layer?: string;
}

const CLASS_DEFAULTS: Record<SfxClass, { maxVoices: number; priority: number; cooldownMs: number; ui: boolean }> = {
  ui_micro: { maxVoices: 2, priority: 1, cooldownMs: 30, ui: true },
  ui_notice: { maxVoices: 2, priority: 2, cooldownMs: 80, ui: true },
  economy: { maxVoices: 3, priority: 3, cooldownMs: 250, ui: false },
  event: { maxVoices: 3, priority: 3, cooldownMs: 250, ui: false },
  alert: { maxVoices: 2, priority: 4, cooldownMs: 1500, ui: false },
  stinger: { maxVoices: 1, priority: 5, cooldownMs: 1000, ui: false },
  world: { maxVoices: 2, priority: 0, cooldownMs: 400, ui: false },
};

/** Explicit cooldowns from §4.10. */
const COOLDOWNS: Record<string, number> = {
  ui_hover: 50,
  ui_click: 30,
  slider_tick: 35,
  cash_register: 250,
  coins_small: 200,
  coins_large: 200,
  notify_info: 1500,
  notify_opportunity: 1500,
  notify_warning: 1500,
  alert_critical: 3000,
};

/** File (KEEP) assets: class and detune policy (0 = musical). */
const FILE_SFX: Record<string, { cls: SfxClass; detune: number }> = {
  build_construct: { cls: 'event', detune: 30 },
  campaign_start: { cls: 'event', detune: 30 },
  cash_register: { cls: 'economy', detune: 30 },
  goal_achieved: { cls: 'event', detune: 0 },
  upgrade: { cls: 'event', detune: 0 },
  notify_info: { cls: 'ui_notice', detune: 0 },
  victory_fanfare: { cls: 'stinger', detune: 0 },
};

function spec(id: string, cls: SfxClass, recipes: string[], extra: Partial<SfxSpec> = {}): SfxSpec {
  const d = CLASS_DEFAULTS[cls];
  return {
    id,
    cls,
    ui: d.ui,
    cooldownMs: COOLDOWNS[id] ?? d.cooldownMs,
    maxVoices: d.maxVoices,
    priority: d.priority,
    fileDetune: FILE_SFX[id]?.detune ?? 0,
    recipes,
    mode: 'fallback',
    ...extra,
  };
}

function build(): Record<string, SfxSpec> {
  const out: Record<string, SfxSpec> = {};
  for (const [id, r] of Object.entries(PROC_RECIPES)) {
    if (r.origin === 'layer') continue;
    out[id] = spec(id, r.cls, [id]);
  }
  for (const [id, r] of Object.entries(FALLBACK_RECIPES)) {
    if (id.startsWith('cash_register_')) continue;
    out[id] = spec(id, r.cls, [id]);
  }
  for (const [id, f] of Object.entries(FILE_SFX)) out[id] ??= spec(id, f.cls, []);
  out.cash_register = spec('cash_register', 'economy', ['cash_register_b', 'cash_register_c'], { mode: 'mix' });
  out.ribbon_cut = spec('ribbon_cut', 'event', ['ribbon_cut'], { layer: 'ribbon_cut_chime' });
  // stingers are music-bus content owned by the MusicDirector, but they can be auditioned here
  for (const [id, r] of Object.entries(STINGER_RECIPES)) out[id] = spec(id, r.cls, [id], { cooldownMs: 0 });
  return out;
}

export const SFX: Readonly<Record<string, SfxSpec>> = build();

export function sfxSpec(id: string): SfxSpec | undefined {
  return SFX[id];
}

/** Ids by class, for the AudioLab. */
export function sfxIdsByClass(): Record<SfxClass, string[]> {
  const out: Record<SfxClass, string[]> = { ui_micro: [], ui_notice: [], economy: [], event: [], alert: [], stinger: [], world: [] };
  for (const s of Object.values(SFX)) out[s.cls].push(s.id);
  for (const k of Object.keys(out) as SfxClass[]) out[k].sort();
  return out;
}

/** Class loudness targets (audio-plan §2.3): momentary max LUFS and the peak ceiling (dBFS). */
export const CLASS_TARGETS: Readonly<Record<SfxClass, { mMax: number; peak: number }>> = {
  ui_micro: { mMax: -30, peak: -12 },
  ui_notice: { mMax: -26, peak: -6 },
  economy: { mMax: -22, peak: -1.5 },
  event: { mMax: -18, peak: -1.5 },
  alert: { mMax: -18, peak: -1.5 },
  stinger: { mMax: -14, peak: -1 },
  world: { mMax: -20, peak: -1.5 },
};

/**
 * The input node for one procedural voice: the recipe's calibrated trim followed by the class peak guard
 * (synth/primitives.ts), connected to `dest`. The same chain is used live (SfxPlayer, stingers) and by
 * the offline level test, so what is measured is what plays.
 */
export function recipeVoiceInput(
  ctx: BaseAudioContext,
  recipeId: string,
  dest: AudioNode,
  opts: { trimDb?: number; guard?: boolean } = {},
): GainNode {
  const def = ALL_RECIPES[recipeId];
  const trim = new GainNode(ctx, { gain: dbToGain(opts.trimDb ?? RECIPE_TRIM_DB[recipeId] ?? 0) });
  if (def && opts.guard !== false) trim.connect(peakGuard(ctx, CLASS_TARGETS[def.cls].peak)).connect(dest);
  else trim.connect(dest);
  return trim;
}
