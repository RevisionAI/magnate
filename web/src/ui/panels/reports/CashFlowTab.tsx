// Cash-flow tab: operating / investing / financing by period, reconciling to
// the change in cash (bridge-spec §4.6.3: upgrades and royalties included; the
// bridge also reports whether every ledger category was classified).

import { CheckCircle2, Download, XCircle } from 'lucide-react';
import { useMemo, useState } from 'react';
import type { CashFlowDto } from '@/bridge/protocol';
import { Button, Panel, Toggle } from '@/ui/components';
import { money } from '@/util/format';
import { ComboChart, Waterfall } from '../_shared-b/charts';
import { ErrorBlock, LoadingBlock, Note, useMoneyFormat } from '../_shared-b/components';
import { downloadCsv } from '../_shared-b/csv';
import { useNames } from '../_shared-b/names';
import { CompanyPicker, PeriodPicker, useColumns, useGameDates, type PeriodState } from '../_shared-b/PeriodPicker';
import { isClosed, toPeriodArgs } from '../_shared-b/periods';
import { cashFlowAddsUp, cashFlowRows, type StatementRow } from '../_shared-b/statement';
import { StatementTable } from '../_shared-b/StatementTable';
import { useEngineQueries } from '../_shared-b/useEngineQueries';
import shared from '../_shared-b/shared.module.css';
import type { ReportsNav } from './index';
import styles from './Reports.module.css';

export function CashFlowTab({ nav }: { nav: ReportsNav }) {
  const [period, setPeriod] = useState<PeriodState>({ granularity: 'quarter', custom: null });
  const [compare, setCompare] = useState(false);
  const dates = useGameDates();
  const names = useNames();
  const fmt = useMoneyFormat();
  const columns = useColumns(period);
  const companyId = nav.companyId;
  const isPlayer = companyId === null || companyId === names.playerId;
  const argsList = useMemo(() => columns.map((c) => ({ period: toPeriodArgs(c), ...(companyId !== null ? { companyId } : {}) })), [columns, companyId]);
  const closed = useMemo(() => columns.map((c) => (dates ? isClosed(c, dates.now) : false)), [columns, dates]);
  const q = useEngineQueries('cashFlow', argsList, closed);
  const data = q.data as (CashFlowDto | undefined)[];
  const rows = useMemo(() => cashFlowRows(data), [data]);
  const latest = data[data.length - 1];
  const latestCol = columns[columns.length - 1];

  const onDrill = (row: StatementRow) => {
    if (!isPlayer || !row.drill || row.drill.kind !== 'ledger') return;
    nav.go('ledger', { categories: row.drill.categories, from: columns[0]?.from, to: latestCol?.to });
  };

  return (
    <div className={shared.page}>
      <div className={shared.toolbar}>
        <PeriodPicker state={period} onChange={setPeriod} />
        <Toggle size="sm" checked={compare} onChange={setCompare} label="Compare with previous" />
        <CompanyPicker value={companyId} onChange={nav.setCompanyId} />
        <span className={shared.spacer} />
        <Button
          size="sm"
          variant="ghost"
          icon={<Download size={14} />}
          disabled={!latest}
          onClick={() => downloadCsv('cash-flow', [['Line', ...columns.map((c) => c.caption)], ...rows.filter((r) => r.kind !== 'header').map((r) => [r.label, ...r.values])])}
        >
          Export CSV
        </Button>
      </div>

      {latest && (
        <div className={styles.reconcile} data-testid="cf-reconcile">
          <Cell label="Cash at start" value={fmt(latest.beginningCash)} op={latestCol?.caption} />
          <Cell label="+ Operations" value={fmt(latest.operating.net, { signed: true })} tone={latest.operating.net} op="selling, buying stock, running costs" />
          <Cell label="+ Investing + financing" value={fmt(latest.investing.net + latest.financing.net, { signed: true })} tone={latest.investing.net + latest.financing.net} op="buildings, capital, loans" />
          <Cell label="= Cash at end" value={fmt(latest.endingCash)} op={latest.reconciles && cashFlowAddsUp(latest) ? 'matches the ledger to the cent' : 'does not match the ledger'} />
        </div>
      )}

      <div className={shared.split}>
        <div className={shared.stack}>
          <Panel title="Cash generated by activity" padding="md" variant="solid">
            <ComboChart
              height={180}
              labels={columns.map((c) => c.label)}
              bars={[
                { id: 'op', label: 'Operations', values: data.map((d) => d?.operating.net ?? null), color: '#5AA7D8' },
                { id: 'inv', label: 'Investing', values: data.map((d) => d?.investing.net ?? null), color: '#D7B766' },
                { id: 'fin', label: 'Financing', values: data.map((d) => d?.financing.net ?? null), color: '#CC79A7' },
              ]}
              yFormat={(v) => money(v, 1)}
            />
          </Panel>
          {q.error && !latest ? <ErrorBlock error={q.error} /> : !latest ? <LoadingBlock rows={12} /> : <StatementTable columns={columns} rows={rows} showDelta={compare} onDrill={onDrill} aria-label="Cash-flow statement" data-testid="cf-table" />}
        </div>
        <div className={shared.stack}>
          {latest && (
            <Panel title={`Bridge · ${latestCol?.caption ?? ''}`} padding="md" variant="solid" accent>
              <Waterfall
                baseline="auto"
                start={{ label: 'Cash at start', value: latest.beginningCash }}
                steps={[
                  { id: 'op', label: 'Operations', amount: latest.operating.net },
                  { id: 'inv', label: 'Investing', amount: latest.investing.net },
                  { id: 'fin', label: 'Financing', amount: latest.financing.net },
                ]}
                end={{ label: 'Cash at end', value: latest.endingCash }}
                format={(v, signed) => fmt(v, { signed, digits: 1 })}
              />
              <div className={styles.books} style={{ marginTop: 12 }}>
                {latest.reconciles ? <CheckCircle2 size={16} color="var(--c-green)" /> : <XCircle size={16} color="var(--c-red)" />}
                <span className={shared.small}>{latest.reconciles ? 'Reconciles: every ledger entry is classified.' : 'Does not reconcile — some ledger categories are unclassified.'}</span>
              </div>
            </Panel>
          )}
          <Note>
            Operating cash differs from net income: stock you buy is cash out today but a cost only when it sells, and buildings are investing cash, not expenses.
          </Note>
        </div>
      </div>
    </div>
  );
}

function Cell({ label, value, op, tone }: { label: string; value: string; op?: string; tone?: number }) {
  return (
    <div className={styles.reconcileCell}>
      <div className={styles.reconcileLabel}>{label}</div>
      <div className={`${styles.reconcileValue} ${tone !== undefined ? (tone > 0 ? shared.pos : tone < 0 ? shared.neg : '') : ''}`}>{value}</div>
      {op && <div className={styles.reconcileOp}>{op}</div>}
    </div>
  );
}
